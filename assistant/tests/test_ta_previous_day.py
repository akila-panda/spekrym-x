"""P10 / X14: the previous-day level is the latest completed trading day.

Bars are generated by formula (no randomness): each trading day has a distinct, known high, so
a test can say which day a level came from just by its price.
"""

from datetime import UTC, date, datetime, timedelta

import pytest

from sx_assistant.ta.sessions import previous_day_levels, session_setups
from sx_core.contracts import Candle
from sx_core.trading_calendar import FX_CALENDAR, TradingCalendar

H1 = timedelta(hours=1)
MON, TUE, WED, THU, FRI = (date(2026, 10, d) for d in (19, 20, 21, 22, 23))
NEXT_MON = date(2026, 10, 26)


def day_high(d: date) -> float:
    return round(1.1000 + 0.0010 * (d.toordinal() % 40), 5)


def day_low(d: date) -> float:
    return round(1.0000 - 0.0010 * (d.toordinal() % 40), 5)


def bar(t: datetime, d: date) -> Candle:
    hi = day_high(d) if t.hour == 12 else 1.1000          # the day's extreme is at 12:00
    lo = day_low(d) if t.hour == 13 else 1.0990
    return Candle(instrument="EUR_USD", tf="H1", time=t, open=1.0995, high=hi, low=lo,
                  close=1.0995, volume=1.0, bid_close=1.0995, ask_close=1.0995, complete=True)


def week(days, *, drop=(), calendar=FX_CALENDAR, extra=()) -> list[Candle]:
    """H1 bars for each date over its trading window, minus ``drop``, plus ``extra`` times."""
    times: set[datetime] = set(extra)
    for d in days:
        win = calendar.trading_window(d)
        if win is None:
            continue
        t = win[0]
        while t < win[1]:
            times.add(t)
            t += H1
    return [bar(t, t.date()) for t in sorted(times - set(drop))]


def at(d: date, h: int) -> datetime:
    return datetime(d.year, d.month, d.day, h, tzinfo=UTC)


def week_days(start: date, n: int = 7) -> list[date]:
    return [start + timedelta(days=i) for i in range(n)]


def high_of(levels) -> float:
    (h,) = [s for s in levels if s.direction == "bearish"]
    return h.geometry.price_high


def low_of(levels) -> float:
    (lo,) = [s for s in levels if s.direction == "bullish"]
    return lo.geometry.price_low


def test_monday_uses_friday_after_a_normal_weekend():
    cs = week(week_days(MON, 8))                             # Mon..Mon, weekend has no bars
    lv = previous_day_levels(cs, NEXT_MON)
    assert high_of(lv) == day_high(FRI) and low_of(lv) == day_low(FRI)
    assert lv[0].known_at == at(FRI, 21)                     # known at Friday's weekly close
    assert lv[0].geometry.t_start == at(FRI, 0)


@pytest.mark.parametrize("on,prev", [(TUE, MON), (WED, TUE), (THU, WED), (FRI, THU)])
def test_tuesday_to_friday_use_the_day_before(on, prev):
    lv = previous_day_levels(week(week_days(MON, 5)), on)
    assert high_of(lv) == day_high(prev)


@pytest.mark.parametrize("on", [date(2026, 10, 24), date(2026, 10, 25)])
def test_weekend_dates_get_the_latest_completed_day(on):
    assert high_of(previous_day_levels(week(week_days(MON, 5)), on)) == day_high(FRI)


def test_missing_friday_bar_falls_back_to_thursday():
    cs = week(week_days(MON, 8), drop={at(FRI, 15)})
    assert high_of(previous_day_levels(cs, NEXT_MON)) == day_high(THU)
    assert not [s for s in session_setups(cs)
                if s.plain_text.startswith("Previous day") and s.known_at == at(FRI, 21)]


def test_friday_bars_after_the_close_are_ignored_and_not_required():
    late = [at(FRI, 21), at(FRI, 22)]                         # after the EDT close
    a = week(week_days(MON, 8), extra=late)
    b = week(week_days(MON, 8))
    assert [(s.id, s.known_at) for s in previous_day_levels(a, NEXT_MON)] == [
        (s.id, s.known_at) for s in previous_day_levels(b, NEXT_MON)]


def test_friday_missing_its_last_bar_before_the_close_is_incomplete():
    cs = week(week_days(MON, 8), drop={at(FRI, 20)})          # last bar before 21:00 close
    assert high_of(previous_day_levels(cs, NEXT_MON)) == day_high(THU)


def test_sunday_evening_stub_is_not_a_day_and_does_not_change_monday():
    sunday = date(2026, 10, 25)
    stub = [at(sunday, 22), at(sunday, 23)]
    cs = week(week_days(MON, 8), extra=stub)
    assert high_of(previous_day_levels(cs, NEXT_MON)) == day_high(FRI)
    assert high_of(previous_day_levels(cs, date(2026, 10, 27))) == day_high(NEXT_MON)
    assert all(s.event_time.date() != sunday for s in session_setups(cs)
               if s.plain_text.startswith("Previous day"))


def test_incomplete_midweek_day_is_skipped():
    cs = week(week_days(MON, 5), drop={at(WED, 3)})
    assert high_of(previous_day_levels(cs, THU)) == day_high(TUE)


def test_holiday_is_skipped_without_using_up_the_lookback():
    cal = TradingCalendar("with_holiday", holidays=frozenset({NEXT_MON}))
    cs = week(week_days(MON, 9), calendar=cal)                # Monday 26th is a holiday
    tue = date(2026, 10, 27)
    assert high_of(previous_day_levels(cs, tue, calendar=cal, max_lookback=1)) == day_high(FRI)


def test_lookback_limit_returns_nothing_rather_than_a_stale_day():
    cs = week(week_days(MON, 5), drop={at(FRI, 5), at(THU, 5), at(WED, 5)})   # Fri, Thu, Wed broken
    assert previous_day_levels(cs, NEXT_MON, max_lookback=3) == []
    assert high_of(previous_day_levels(cs, NEXT_MON, max_lookback=4)) == day_high(TUE)


def test_no_data_before_the_date_gives_nothing():
    assert previous_day_levels(week([MON]), MON) == []


@pytest.mark.parametrize("friday,close_utc_hour", [
    (date(2026, 3, 6), 22),    # US still on EST; UK not on BST yet
    (date(2026, 3, 13), 21),   # US on EDT (since 8 March); UK still on GMT: the mismatch weeks
    (date(2026, 10, 23), 21),  # UK on BST until 25 Oct, US on EDT
    (date(2026, 10, 30), 21),  # UK on GMT since 25 Oct; US still EDT until 1 Nov
    (date(2026, 11, 6), 22),   # both on winter time
])
def test_friday_close_follows_new_york_time_across_dst_weeks(friday, close_utc_hour):
    start = friday - timedelta(days=4)
    cs = week(week_days(start, 8))
    nxt = start + timedelta(days=7)
    lv = previous_day_levels(cs, nxt)
    assert high_of(lv) == day_high(friday)
    assert lv[0].known_at == at(friday, close_utc_hour)


def test_us_dst_start_weekend_does_not_break_monday_levels():
    fri, mon = date(2026, 3, 6), date(2026, 3, 9)             # clocks go forward on Sunday 8 March
    cs = week(week_days(fri - timedelta(days=4), 8))
    assert high_of(previous_day_levels(cs, mon)) == day_high(fri)


def test_the_unknown_instrument_needs_an_explicit_calendar():
    cs = [c.model_copy(update={"instrument": "BTC_USD"}) for c in week([MON, TUE])]
    with pytest.raises(ValueError, match="no trading calendar"):
        previous_day_levels(cs, WED)
    assert previous_day_levels(cs, WED, calendar=FX_CALENDAR)


def test_instrument_with_a_sunday_to_thursday_week():
    cal = TradingCalendar("sun_thu", weekdays=frozenset({6, 0, 1, 2, 3}), close_weekday=3,
                          close_tz="UTC")
    sun = date(2026, 10, 25)
    cs = week(week_days(sun - timedelta(days=3), 5), calendar=cal)      # Thu 22 .. Mon 26
    assert high_of(previous_day_levels(cs, date(2026, 10, 26), calendar=cal)) == day_high(sun)


def test_session_setups_and_previous_day_levels_agree():
    cs = week(week_days(MON, 8))
    from_sessions = {s.id for s in session_setups(cs) if s.plain_text.startswith("Previous day")}
    assert {s.id for s in previous_day_levels(cs, NEXT_MON)} <= from_sessions


def test_previous_day_levels_are_causal(assert_causal):
    cs = week(week_days(MON, 8))
    assert_causal(lambda c: [s for s in session_setups(c) if s.plain_text.startswith("Prev")], cs)
